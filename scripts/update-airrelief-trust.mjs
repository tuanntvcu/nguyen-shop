import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {gql,files,dir} from './airrelief-store.mjs';
const names=['sections/altaeron-pdp-dialfit.liquid','sections/altaeron-pdp-massager.liquid','assets/altaeron-pdp-massager.js','templates/product.altaeron-massager.json'];
const remote=await files(names);
await fs.writeFile(`${dir}/trust-before.json`,JSON.stringify(remote,null,2));
const source=remote.find(f=>f.filename===names[0]).body.content;
const start=source.indexOf('        <div class="apdp-buy__trust">');
assert.ok(start>=0);
const trust=source.slice(start,source.indexOf('      </aside>',start)).trim();
let section=remote.find(f=>f.filename===names[1]).body.content;
const existing=section.match(/<div class="apdp-buy__trust">[\s\S]*?<\/div>(?=<\/aside>)/);
assert.ok(existing,'Locate existing trust block');section=section.replace(existing[0],trust);
const social=`{%- capture social_proof_count -%}<strong data-apdp-social-proof-count></strong>{%- endcapture -%}<p class="apdp-social-proof" data-apdp-social-proof data-store-date="{{ 'now' | date: '%Y-%m-%d' }}" data-store-utc-offset="{{ 'now' | date: '%z' }}" hidden>{{ 'altaeron_pdp.buy.social_proof_html' | t: count: social_proof_count }}</p>`;
assert.ok(!section.includes('data-apdp-social-proof-count'));
section=section.replace('{% endform %}',`${social}{% endform %}`);
section=section.replace('</style>','\n#AltaeronPdp-{{ section.id }} .apdp-buy__trust{grid-template-columns:repeat(2,minmax(0,1fr));gap:12px 18px}\n#AltaeronPdp-{{ section.id }} .apdp-buy__trust>:first-child{display:flex}\n</style>');
let js=remote.find(f=>f.filename===names[2]).body.content;
assert.ok(!js.includes('    initSocialProof(root);'));
js=js.replace('    initHeroExperience(root);','    initHeroExperience(root);\n    initSocialProof(root);');
await fs.writeFile(names[1],section);await fs.writeFile(names[2],js);
const result=await gql(`mutation($files:[OnlineStoreThemeFilesUpsertFileInput!]!){themeFilesUpsert(themeId:"gid://shopify/OnlineStoreTheme/140538314813",files:$files){upsertedThemeFiles{filename}userErrors{field message}}}`,{files:[{filename:names[1],body:{type:'TEXT',value:section}},{filename:names[2],body:{type:'TEXT',value:js}}]});
const after=await files([names[0],names[3]]);for(const f of after)assert.equal(f.checksumMd5,remote.find(o=>o.filename===f.filename).checksumMd5);
console.log(JSON.stringify({result,dialfitUnchanged:true,mediaTemplateUnchanged:true}));
